# Sourced by pixi activation (pixi.toml [activation] scripts).
#
# On the Jetson (l4t environment) keep ROS 2 / Fast DDS traffic off Wi-Fi: everything goes over
# Ethernet (the wired LAN, or the long-range radio link bridged to Ethernet). Fast DDS otherwise
# uses every interface, and the Jetson is also on eduroam: half the camera traffic to the ground
# station left over Wi-Fi (5.4 GB in 25 min).
#
# The whitelist is built here from the interfaces that exist now: loopback plus every IPv4
# address on a non-wireless, non-virtual interface (eno1, a USB Ethernet adapter...), so a new
# network or address needs no edit. Fast DDS 2.6 filters by address, not interface name.
#   - No wired address at activation (cable out): no profile, Fast DDS's defaults.
#   - BILLEE_DDS_ALL_INTERFACES=1: no profile (e.g. astronaut mode, if ROS ever needs Wi-Fi).
#   - An explicit FASTRTPS_DEFAULT_PROFILES_FILE wins.
# The ground station is not restricted, so it can join from any address.
if [ "${PIXI_ENVIRONMENT_NAME:-}" = "l4t" ] && [ -z "${BILLEE_DDS_ALL_INTERFACES:-}" ] \
  && [ -z "${FASTRTPS_DEFAULT_PROFILES_FILE:-}" ]; then
  _billee_dds_profile="${TMPDIR:-/tmp}/billee-fastdds-$(id -u).xml"
  if python3 - "$_billee_dds_profile" <<'PY'
import fcntl, os, socket, struct, sys

def ipv4(ifname):
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:  # SIOCGIFADDR
        raw = fcntl.ioctl(s.fileno(), 0x8915, struct.pack("256s", ifname[:15].encode()))
        return socket.inet_ntoa(raw[20:24])
    except OSError:
        return None
    finally:
        s.close()

VIRTUAL = ("lo", "docker", "veth", "br-", "virbr", "can", "vcan", "l4tbr", "usb", "rndis",
           "dummy", "tun", "tap", "wg")
wired = []
for name in sorted(os.listdir("/sys/class/net")):
    if name.startswith(VIRTUAL) or os.path.exists(f"/sys/class/net/{name}/wireless"):
        continue
    addr = ipv4(name)
    if addr:
        wired.append((name, addr))
if not wired:
    sys.exit(1)  # nothing wired up: leave Fast DDS on its defaults
entries = "\n".join(f"        <address>{a}</address>  <!-- {n} -->" for n, a in wired)
xml = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by ros2_ws/dds_env.sh at pixi activation: ROS traffic on loopback + wired only. -->
<profiles xmlns="http://www.eprosima.com/XMLSchemas/fastRTPS_Profiles">
  <transport_descriptors>
    <transport_descriptor>
      <transport_id>billee_shm</transport_id>
      <type>SHM</type>
      <!-- Fast DDS's default 512 KB segment is smaller than one RealSense colour frame
           (640x480 rgb8 = 900 KB): every frame then fell back to fragmented UDP on loopback,
           and with best-effort QoS on a busy Jetson a third of them were lost (12 of 30 fps,
           gaps up to 0.8 s: the stuttering arm camera). 16 MB holds several frames: 30 of 30. -->
      <segment_size>16777216</segment_size>
    </transport_descriptor>
    <transport_descriptor>
      <transport_id>billee_wired_udp</transport_id>
      <type>UDPv4</type>
      <interfaceWhiteList>
        <address>127.0.0.1</address>
{entries}
      </interfaceWhiteList>
    </transport_descriptor>
  </transport_descriptors>
  <participant profile_name="billee_wired" is_default_profile="true">
    <rtps>
      <userTransports>
        <transport_id>billee_shm</transport_id>
        <transport_id>billee_wired_udp</transport_id>
      </userTransports>
      <useBuiltinTransports>false</useBuiltinTransports>
    </rtps>
  </participant>
</profiles>
"""
tmp = sys.argv[1] + f".{os.getpid()}"
with open(tmp, "w") as f:
    f.write(xml)
os.replace(tmp, sys.argv[1])
PY
  then
    export FASTRTPS_DEFAULT_PROFILES_FILE="$_billee_dds_profile"
  fi
  unset _billee_dds_profile
fi
